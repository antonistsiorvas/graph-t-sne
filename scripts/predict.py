"""Predict the time of each phase on coPapersDBLP BEFORE running it.

    python3 scripts/predict.py     -> results/prediction_coPapersDBLP.md and .csv

Model (reference graph: com-Amazon, unweighted like coPapersDBLP, and like it
too large for the per-core cache; k49 is weighted, so its P is bisection, and
its data fits in cache, so its per-unit costs are optimistic):

  sequential:  time = (measured time per unit on com-Amazon) x (units on coPapersDBLP)
      P without mirror, mirror, attraction   per nonzero (nnz)
      build, centers of mass, gradient       per point (n)
      walk                                   per term; terms = n x terms per point,
                                             terms per point assumed equal to
                                             com-Amazon's (same L = 8, ~8 points/leaf)
  parallel:    each phase gets the speedup it had on com-Amazon for the same
               version and p; the mirror stays sequential (Amdahl), so P is
               predicted as mirror + (rest of P) / (its com-Amazon speedup).
"""
import csv
import math

REF = "com-Amazon"
TARGET = "coPapersDBLP"
N_T, NNZ_T = 540_486, 2 * 15_245_729          # README: nodes, edges (stored twice)
TERMS_REF = 584                                # results/terms_per_point.txt, com-Amazon
PHASES = ["P", "mirror", "attr", "build", "mass", "walk", "grad"]

rows = {}
for r in csv.DictReader(open("results/timings_median.csv")):
    rows[(r["graph"], r["version"], int(r["p"]))] = r

def t(version, p, phase):
    return float(rows[(REF, version, p)][phase])

seq = rows[(REF, "seq", 1)]
n_A, nnz_A = int(seq["n"]), int(seq["nnz"])
L_T = max(1, round(math.log(N_T / 8) / math.log(4)))      # tree_depth(n)

# ---- sequential prediction ---------------------------------------------
rest_A = t("seq", 1, "P") - t("seq", 1, "mirror")          # P without mirror
pred = {("seq", 1): {
    "mirror": t("seq", 1, "mirror") / nnz_A * NNZ_T,
    "Prest":  rest_A / nnz_A * NNZ_T,
    "attr":   t("seq", 1, "attr")  / nnz_A * NNZ_T,
    "build":  t("seq", 1, "build") / n_A * N_T,
    "mass":   t("seq", 1, "mass")  / n_A * N_T,
    "walk":   t("seq", 1, "walk")  / (n_A * TERMS_REF) * (N_T * TERMS_REF),
    "grad":   t("seq", 1, "grad")  / n_A * N_T,
}}
s = pred[("seq", 1)]
s["P"] = s["mirror"] + s["Prest"]

# ---- parallel prediction: com-Amazon's speedup per phase ---------------
for (g, v, p) in rows:
    if g != REF or v == "seq":
        continue
    rest_vp = t(v, p, "P") - t(v, p, "mirror")
    d = {"mirror": s["mirror"] * t(v, p, "mirror") / t("seq", 1, "mirror"),
         "Prest":  s["Prest"] * rest_vp / rest_A}
    d["P"] = d["mirror"] + d["Prest"]
    for ph in ["attr", "build", "mass", "walk", "grad"]:
        d[ph] = s[ph] * t(v, p, ph) / t("seq", 1, ph)
    pred[(v, p)] = d

def total(d):
    return sum(d[ph] for ph in ["P", "attr", "build", "mass", "walk", "grad"])

# ---- write -------------------------------------------------------------
with open(f"results/prediction_{TARGET}.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["graph", "version", "p"] + PHASES + ["total"])
    for (v, p), d in sorted(pred.items()):
        w.writerow([TARGET, v, p] + [f"{d[ph]:.6f}" for ph in PHASES] + [f"{total(d):.6f}"])

def ms(x):
    return f"{x * 1e3:,.0f} ms" if x >= 0.01 else f"{x * 1e3:.1f} ms"

nnz_ratio, n_ratio = NNZ_T / nnz_A, N_T / n_A
lines = [
    f"# Prediction for {TARGET}, made before running it",
    "",
    f"Generated by `scripts/predict.py` from `results/timings_median.csv` "
    f"(medians of 5 runs) and `results/terms_per_point.txt`.",
    "",
    f"- {TARGET}: n = {N_T:,}, nnz = {NNZ_T:,}, unweighted, degree 1-3,299; "
    f"default depth L = {L_T}.",
    f"- Reference {REF}: n = {n_A:,}, nnz = {nnz_A:,}. "
    f"Ratios: n x{n_ratio:.2f}, nnz x{nnz_ratio:.1f}.",
    "",
    "| phase | proportional to | seq | OpenMP 12 | OpenCilk 12 | Pthreads 12 |",
    "|---|---|---|---|---|---|",
]
basis = {"P": "nnz", "mirror": "nnz (sequential in all)", "attr": "nnz",
         "build": "n", "mass": "n", "walk": "n x terms/point", "grad": "n"}
names = {"P": "P (incl. mirror)", "mirror": "  of which mirror", "attr": "attraction",
         "build": "tree build", "mass": "centers of mass", "walk": "walk", "grad": "gradient"}
for ph in PHASES:
    lines.append(f"| {names[ph]} | {basis[ph]} | {ms(s[ph])} | "
                 + " | ".join(ms(pred[(v, 12)][ph]) for v in ["omp", "cilk", "pth"]) + " |")
lines.append(f"| **total** | | **{ms(total(s))}** | "
             + " | ".join(f"**{ms(total(pred[(v, 12)]))}**" for v in ["omp", "cilk", "pth"]) + " |")
lines += [
    "",
    "All thread counts (1, 2, 4, 8, 12) are in the .csv, for the comparison plot.",
    "",
    "## Expected differences from this model",
    "",
    f"- **The walk is still the largest phase** "
    f"({s['walk'] / total(s):.0%} of the sequential time), but P grows "
    f"{nnz_ratio:.1f}x while the walk grows {n_ratio:.1f}x, so P's share rises from "
    f"{t('seq', 1, 'P') / sum(t('seq', 1, ph) for ph in ['P','attr','build','mass','walk','grad']):.0%} "
    f"to {s['P'] / total(s):.0%}.",
    "- **P and attraction may be faster per nonzero than predicted.** The median degree is "
    "34 (com-Amazon: 4), so the per-row overhead (loop setup, the min/max pass, reading "
    "y_i) is shared by 8x more entries. Risk the other way: the matrix (over 1 GB with "
    "P, Pc and mirror) streams from memory, as com-Amazon's (74 MB) already did.",
    "- **P's speedup is capped by the sequential mirror.** At 12 threads the mirror is "
    f"predicted at {ms(pred[('omp', 12)]['mirror'])} of P's "
    f"{ms(pred[('omp', 12)]['P'])} (OpenMP).",
    "- **Attraction: degree imbalance.** Rows of degree up to 3,299 in chunks of 256 rows; "
    "if high-degree rows are clustered in the numbering, one chunk can be much heavier "
    "than the rest and finish last.",
    "- **Walk: the shape of the embedding.** Terms per point are assumed equal to "
    "com-Amazon's (584). A more clustered Y0 gives crowded leaves and more terms.",
    "- **Tiny phases** (build, centers of mass, gradient) are dominated by thread "
    "overhead at 12 threads, which does not grow with n; scaling them by the work "
    "overestimates them, but they are a few ms either way.",
    "- **Memory**: about 1.3 GB for the matrix arrays; the machine has 7.6 GB.",
]
open(f"results/prediction_{TARGET}.md", "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
